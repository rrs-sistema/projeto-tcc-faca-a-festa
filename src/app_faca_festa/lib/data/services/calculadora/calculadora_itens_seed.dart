class CalculadoraItensSeedService {
  static const String collectionItensBase = 'calculadora_itens_base';
  static const String collectionEventoItens = 'calculadora_evento_itens';

  final FirebaseFirestore _firestore;

  CalculadoraItensSeedService({
    required FirebaseFirestore firestore,
  }) : _firestore = firestore;

  Future<void> popularSeeds({
    bool sobrescrever = false,
  }) async {
    await _popularColecao(
      collectionPath: collectionItensBase,
      seeds: calculadoraItensBaseSeed,
      sobrescrever: sobrescrever,
    );

    await _popularColecao(
      collectionPath: collectionEventoItens,
      seeds: calculadoraEventoItensSeed,
      sobrescrever: sobrescrever,
    );

    developer.log(
      'Seeds da calculadora populados com sucesso. '
      'sobrescrever=$sobrescrever | '
      'itensBase=${calculadoraItensBaseSeed.length} | '
      'eventoItens=${calculadoraEventoItensSeed.length}',
      name: 'CalculadoraItensSeedService',
    );
  }

  Future<void> _popularColecao({
    required String collectionPath,
    required List<Map<String, dynamic>> seeds,
    required bool sobrescrever,
  }) async {
    var batch = _firestore.batch();
    var batchWrites = 0;
    var totalCriados = 0;
    var totalAtualizados = 0;
    var totalIgnorados = 0;

    final collectionRef = _firestore.collection(collectionPath);

    for (final seed in seeds) {
      final id = _parseString(seed['id']);

      if (id.isEmpty) {
        totalIgnorados++;
        continue;
      }

      final documentRef = collectionRef.doc(id);
      final documentSnapshot = await documentRef.get();

      if (documentSnapshot.exists && !sobrescrever) {
        totalIgnorados++;
        continue;
      }

      final data = Map<String, dynamic>.from(seed);

      data['updated_at'] = FieldValue.serverTimestamp();

      if (!documentSnapshot.exists) {
        data['created_at'] = FieldValue.serverTimestamp();
        totalCriados++;
      } else {
        totalAtualizados++;
      }

      batch.set(
        documentRef,
        data,
        SetOptions(merge: true),
      );

      batchWrites++;

      if (batchWrites >= 450) {
        await batch.commit();
        batch = _firestore.batch();
        batchWrites = 0;
      }
    }

    if (batchWrites > 0) {
      await batch.commit();
    }

    developer.log(
      'Seed finalizado para $collectionPath | '
      'criados=$totalCriados | '
      'atualizados=$totalAtualizados | '
      'ignorados=$totalIgnorados | '
      'sobrescrever=$sobrescrever',
      name: 'CalculadoraItensSeedService',
    );
  }

  String _parseString(dynamic value) {
    if (value == null) {
      return '';
    }

    if (value is String) {
      return value.trim();
    }

    return value.toString().trim();
  }
}

