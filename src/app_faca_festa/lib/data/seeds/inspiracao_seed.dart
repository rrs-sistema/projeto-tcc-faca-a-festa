  static Map<String, dynamic> _insp({
    required String id,
    required String titulo,
    required String descricao,
    required String imagem,
    required List<String> galeria,
    required List<String> tags,
    required List<String> paleta,
    required String categoria,
    required String categoriaId,
    required List<({String id, String slug, String nome})> eventos,
    required String estilo,
    required String faixa,
    required String dificuldade,
    required List<String> fornecedores,
    required List<String> catsFornecedor,
    required List<Map<String, dynamic>> tarefas,
    required List<Map<String, dynamic>> orcamento,
    bool destaque = false,
    int ordem = 100,
  }) {
    final ids = eventos.map((e) => e.id).toList();
    final nomes = eventos.map((e) => e.nome).toList();
    final slugs = <String>[];
    for (final evento in eventos) {
      final underscore = evento.slug.replaceAll('-', '_');
      final hyphen = evento.slug.replaceAll('_', '-');
      for (final extra in [evento.slug, underscore, hyphen]) {
        if (!slugs.contains(extra)) slugs.add(extra);
      }
    }
    final primario = eventos.first;
    return {
      'id': id,
      'titulo': titulo,
      'descricao': descricao,
      'imagemUrl': imagem,
      'galeriaUrls': galeria,
      'tags': tags,
      'paletaCores': paleta,
      'categoria': categoria,
      'categoriaId': categoriaId,
      'tipoEventoId': primario.id,
      'tipoEvento': primario.nome,
      'tipoEventoNormalizado': primario.slug.replaceAll('-', '_'),
      'tipoEventoSlug': primario.slug.replaceAll('-', '_'),
      'tipoEventoNome': primario.nome,
      'tipoEventoIds': ids,
      'tipoEventoSlugs': slugs,
      'tipoEventoNomes': nomes,
      'estilo': estilo,
      'faixaCusto': faixa,
      'nivelDificuldade': dificuldade,
      'fornecedoresRelacionados': fornecedores,
      'categoriasFornecedorSugeridas': catsFornecedor,
      'tarefasSugeridas': tarefas,
      'itensOrcamentoSugeridos': orcamento,
      'destaque': destaque,
      'ativo': true,
      'publicado': true,
      'deletado': false,
      'favorito': false,
      'ordem': ordem,
      'origem': 'catalogo_festas',
    };
  }

